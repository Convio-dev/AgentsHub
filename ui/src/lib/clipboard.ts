/**
 * Clipboard helper with a synchronous fallback.
 *
 * WebView2 exposes `navigator.clipboard`, but it rejects when the document is not focused or the
 * permission is denied, which happens routinely for a chat window opened from the tray. The
 * textarea + execCommand path still works there, so copy buttons stay functional either way.
 */

export async function copyToClipboard(text: string): Promise<boolean> {
  if (!text) return false;

  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // fall through to the legacy path
  }

  try {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', '');
    area.style.position = 'fixed';
    area.style.top = '-1000px';
    area.style.opacity = '0';
    document.body.appendChild(area);
    area.select();
    const copied = document.execCommand('copy');
    document.body.removeChild(area);
    return copied;
  } catch {
    return false;
  }
}
